import type { Report, Row } from "./evaluate.js";
import type { Fixture } from "./fixtures.js";

interface TargetStats {
  readonly id: string;
  readonly version: string;
  readonly kept: number;
  readonly drops: number;
  readonly altered: number;
  readonly other: number;
}

function statsFor(report: Report): TargetStats[] {
  return report.targets.map((t) => {
    const rows = report.rows.filter((r) => r.targetId === t.id);
    return {
      id: t.id,
      version: t.libraryVersion,
      kept: rows.reduce((n, r) => n + r.cases.filter((c) => c.enforced).length, 0),
      drops: rows.filter((r) => r.outcome === "silent_drop").length,
      altered: rows.filter((r) => r.validRejected.length > 0).length,
      other: rows.filter((r) => ["reject", "missing", "uncompilable"].includes(r.outcome)).length,
    };
  });
}

function cell(row: Row | undefined, constraint: string): string {
  const c = row?.cases.find((x) => x.constraint === constraint);
  if (!row || !c) return "?";
  if (!c.enforced) return "**dropped**";
  return row.validRejected.length > 0 ? "kept†" : "kept";
}

/** Renders results as Markdown. Every number comes from `report`. */
export function renderSummary(report: Report, fixtures: Fixture[]): string {
  const stats = statsFor(report).sort((a, b) => b.kept - a.kept || a.id.localeCompare(b.id));
  const lines: string[] = [];
  lines.push("# Results", "");
  lines.push(
    `${fixtures.length} fixtures, ${report.caseCount} constraint cases, ${report.targets.length} library and provider pairs. ` +
      "Generated by `pnpm census evaluate captures results` from the raw requests in `captures/`.",
    "",
  );
  lines.push("## By target", "");
  lines.push(
    "| Target | Constraints kept | Fixtures with a drop | Fixtures where a valid value is now rejected | Versions |",
  );
  lines.push("| --- | --- | --- | --- | --- |");
  for (const s of stats) {
    lines.push(
      `| \`${s.id}\` | ${s.kept}/${report.caseCount} | ${s.drops} | ${s.altered} | ${s.version} |`,
    );
  }
  lines.push("");

  const imperfect = stats.filter((s) => s.kept < report.caseCount || s.altered > 0 || s.other > 0);
  const clean = stats.filter((s) => !imperfect.includes(s));
  if (clean.length > 0) {
    lines.push(
      `${clean.map((s) => `\`${s.id}\``).join(", ")} passed every schema through without a change that matters.`,
      "",
    );
  }

  lines.push("## Constraint by constraint", "");
  lines.push("Only targets that lost or changed something are shown.", "");
  lines.push(`| Fixture | Keyword | ${imperfect.map((s) => `\`${s.id}\``).join(" | ")} |`);
  lines.push(`| --- | --- | ${imperfect.map(() => "---").join(" | ")} |`);
  for (const f of fixtures) {
    for (const c of f.cases) {
      const keyword = c.constraint.split("/").at(-1);
      const cells = imperfect.map((s) =>
        cell(
          report.rows.find((r) => r.targetId === s.id && r.fixtureId === f.id),
          c.constraint,
        ),
      );
      lines.push(`| ${f.id} | \`${keyword}\` | ${cells.join(" | ")} |`);
    }
  }
  lines.push("");
  lines.push(
    "† The constraint still rejects the bad value, but the outgoing schema also rejects a valid value. See below.",
    "",
  );

  const altered = report.rows.filter((r) => r.validRejected.length > 0);
  if (altered.length > 0) {
    lines.push("## Valid values that the outgoing schema rejects", "");
    lines.push(
      "These schemas got stricter or broke, not weaker. A model that obeys them cannot send a value that the original schema allows.",
      "",
    );
    lines.push("| Target | Fixture | Rejected valid value |");
    lines.push("| --- | --- | --- |");
    for (const r of altered) {
      const f = fixtures.find((x) => x.id === r.fixtureId);
      for (const i of r.validRejected) {
        lines.push(`| \`${r.targetId}\` | ${r.fixtureId} | \`${JSON.stringify(f?.valid[i])}\` |`);
      }
    }
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}
