"""Write results/models/by-model.md from results/models/results.json.

    python3 harness/model_table.py

The model sweep (`--all-models`) captures every fixture with several models per
provider. This table shows whether the score for a library and provider depends on
the model name, and which constraints change when it does.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    report = json.loads((ROOT / "results/models/results.json").read_text())
    total = report["caseCount"]
    rows = report["rows"]

    kept: dict[str, int] = defaultdict(int)
    altered: dict[str, int] = defaultdict(int)
    enforced: dict[tuple[str, str], list[bool]] = {}
    for r in rows:
        kept[r["targetId"]] += sum(c["enforced"] for c in r["cases"])
        altered[r["targetId"]] += 1 if r["validRejected"] else 0
        enforced[(r["targetId"], r["fixtureId"])] = [c["enforced"] for c in r["cases"]]

    paths: dict[str, list[dict]] = defaultdict(list)
    for t in report["targets"]:
        paths[t["id"].split("@", 1)[0]].append(t)

    lines = [
        "# Results by model",
        "",
        f"Every library and provider path, captured again with {len(report['targets'])} library and model pairs. "
        "The first model of each path is the one in the main results. "
        "Generated by `harness/model_table.py` from `results/models/results.json`.",
        "",
        f"| Path | Constraints kept, of {total} (schemas made stricter) | Same for every model |",
        "| --- | --- | --- |",
    ]
    differs: list[tuple[str, list[dict]]] = []
    for path in sorted(paths):
        targets = paths[path]
        cells = ", ".join(f"`{t['model']}` {kept[t['id']]} ({altered[t['id']]})" for t in targets)
        same = len({(kept[t["id"]], altered[t["id"]]) for t in targets}) == 1
        lines.append(f"| `{path}` | {cells} | {'yes' if same else '**no**'} |")
        if not same:
            differs.append((path, targets))

    for path, targets in differs:
        first = targets[0]
        lines += ["", f"## `{path}`", "", f"Constraints that differ from `{first['model']}`:", ""]
        fixtures = sorted({fid for (tid, fid) in enforced if tid == first["id"]})
        for t in targets[1:]:
            changed = [f for f in fixtures if enforced[(t["id"], f)] != enforced[(first["id"], f)]]
            if changed:
                lines.append(f"- `{t['model']}`: {', '.join(changed)}")

    out = ROOT / "results/models/by-model.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(paths)} paths, {len(differs)} depend on the model")


if __name__ == "__main__":
    main()
